CREATE TABLE IF NOT EXISTS textbook_co_receipts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  organization_id BIGINT UNSIGNED NOT NULL,
  source_kind VARCHAR(32) NOT NULL,
  receipt_path VARCHAR(32) NOT NULL,
  co_delivery_reference VARCHAR(120) NOT NULL,
  received_on DATE NOT NULL,
  remarks VARCHAR(500) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
  created_by BIGINT UNSIGNED NOT NULL,
  submitted_at TIMESTAMP NULL DEFAULT NULL,
  inspected_by BIGINT UNSIGNED NULL,
  inspection_reference VARCHAR(160) NULL,
  inspection_note VARCHAR(500) NULL,
  inspected_at TIMESTAMP NULL DEFAULT NULL,
  accepted_by BIGINT UNSIGNED NULL,
  custodian_employee_id BIGINT UNSIGNED NULL,
  signed_acceptance_reference VARCHAR(160) NULL,
  accepted_on DATE NULL,
  accepted_at TIMESTAMP NULL DEFAULT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_co_delivery_org (organization_id, co_delivery_reference),
  KEY idx_co_receipts_org_status (organization_id, status, id),
  FOREIGN KEY (organization_id) REFERENCES organizations(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (inspected_by) REFERENCES users(id),
  FOREIGN KEY (accepted_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
